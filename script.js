/* ==========================================================================
   Apply language
   ========================================================================== */
function applyLanguage(lang){
  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const entry = translations[el.getAttribute("data-i18n")];
    if (entry && entry[lang]) el.textContent = entry[lang];
  });

  try { localStorage.setItem("aplus-lang", lang); } catch(e) {}
}

function initLanguage(){
  let lang = "sv";
  try { lang = localStorage.getItem("aplus-lang") || "sv"; } catch(e) {}
  applyLanguage(lang);

  const toggle = document.getElementById("langToggle");
  if (!toggle) return;
  toggle.addEventListener("click", () => {
    const current = document.documentElement.getAttribute("lang") === "en" ? "en" : "sv";
    applyLanguage(current === "sv" ? "en" : "sv");
  });
}

/* ==========================================================================
   Header condense on scroll
   ========================================================================== */
function initHeader(){
  const header = document.querySelector(".site-header");
  if (!header) return;
  const onScroll = () => header.classList.toggle("is-scrolled", window.scrollY > 40);
  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });
}

/* ==========================================================================
   Mobile menu
   ========================================================================== */
function initMenu(){
  const menuToggle = document.getElementById("menuToggle");
  const nav = document.getElementById("mainNav");
  if (!menuToggle || !nav) return;
  menuToggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
  });
  nav.querySelectorAll("a").forEach(a => {
    a.addEventListener("click", () => {
      nav.classList.remove("open");
      menuToggle.setAttribute("aria-expanded", "false");
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initLanguage();
  initHeader();
  initMenu();
});
